#requires -Version 5.1
# Opens each Settings page in its own Settings window and saves a PNG of it.
# A solid backdrop sits behind the window while capturing, so no desktop shows at the edges.
# Settings run with a throwaway APPDATA, so your real configuration is never read or changed.
# Afterwards it writes screenshots.md, listing every PNG in the output folder.
$ErrorActionPreference='Stop'
. (Join-Path $PSScriptRoot 'lib\arguments.ps1')
$pages = @('general','tray','overlays','hotkeys','advanced','about')
$titles = @{ general = 'General'; tray = 'Tray icons'; overlays = 'Desktop overlays'; hotkeys = 'Keyboard shortcuts'; advanced = 'Advanced'; about = 'About' }
$options = Read-Arguments $args @{ 'out' = 'string'; 'exe' = 'string'; 'no-build' = 'switch'; 'page' = 'list'; 'theme' = 'list'; 'width' = 'string'; 'height' = 'string'; 'delay' = 'string'; 'index-only' = 'switch' } @"
Usage: screenshot-settings.ps1 [options]
  --out DIR         Output folder (default: screenshots in the repository root).
  --exe PATH        Use this executable instead of building the x64 release.
  --no-build        Skip the release build and use the last one.
  --page LIST       Pages to capture: $($pages -join ', ') (default: all).
  --theme LIST      light, dark (default: both).
  --width PX        Window client width (default: 1080; below 1000 shows the compact pane).
  --height PX       Window client height (default: 780; use more to capture long pages fully).
  --delay MS        Wait after the window appears before capturing (default: 2000).
  --index-only      Only rewrite screenshots.md from the PNGs already in the output folder.
"@
$root = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$out = if ($options['out']) { $options['out'] } else { Join-Path $root 'screenshots' }
$selected = if ($options['page']) { @($options['page']) } else { $pages }
Assert-Choice 'page' $selected $pages
$themes = if ($options['theme']) { @($options['theme']) } else { @('light','dark') }
Assert-Choice 'theme' $themes @('light','dark')
$width = if ($options['width']) { [int]$options['width'] } else { 1080 }
$height = if ($options['height']) { [int]$options['height'] } else { 780 }
# Close to the Mica base colours, so the corners blend in.
$backdrop = @{ light = '#F3F3F3'; dark = '#202020' }
$delay = if ($options['delay']) { [int]$options['delay'] } else { 2000 }


# Builds screenshots.md from whatever PNGs are in the folder. Light/dark pairs (-light/-dark
# suffix) share a row. Overview images come first, then the Settings pages in menu order,
# then anything else.
function Write-ScreenshotIndex([string]$Folder) {
    $groups = [ordered]@{}
    foreach ($file in Get-ChildItem -Path $Folder -Filter *.png | Sort-Object Name) {
        $stem = $file.BaseName
        $theme = ''
        if ($stem -match '^(.*)-(light|dark)$') { $stem = $Matches[1]; $theme = $Matches[2] }
        if (-not $groups.Contains($stem)) { $groups[$stem] = @{} }
        $groups[$stem][$theme] = $file.Name
    }
    $overview = @(); $settings = @(); $other = @()
    foreach ($stem in $groups.Keys) {
        $name = $stem -replace '^WindowsVirtualDesktopHelper-', ''
        if ($name -match '(^|-)overview($|-)') {
            $overview += ,@('Overview', $groups[$stem])
        } elseif ($name -match '^Screenshot-\d+-(.+)$') {
            $title = if ($titles.ContainsKey($Matches[1])) { $titles[$Matches[1]] } else { $Matches[1] }
            $settings += ,@($title, $groups[$stem])
        } else {
            $other += ,@((Get-Culture).TextInfo.ToTitleCase(($name -replace '[-_]+', ' ')), $groups[$stem])
        }
    }
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add('# Screenshots'); $lines.Add('')
    $lines.Add('Generated by `scripts/screenshot-settings.ps1` from the images in this folder. Run it with `--index-only` to refresh this page after adding or renaming images.')
    function Add-Entry($Heading, $Level, $Title, $Images) {
        $lines.Add(''); $lines.Add("$('#' * $Level) $Heading"); $lines.Add('')
        $themes = @('light', 'dark') | Where-Object { $Images.ContainsKey($_) }
        if ($themes) {
            $lines.Add('| ' + (($themes | ForEach-Object { (Get-Culture).TextInfo.ToTitleCase($_) }) -join ' | ') + ' |')
            $lines.Add('| ' + (($themes | ForEach-Object { '---' }) -join ' | ') + ' |')
            $lines.Add('| ' + (($themes | ForEach-Object { "![$Title ($_)]($($Images[$_] -replace ' ', '%20'))" }) -join ' | ') + ' |')
        }
        if ($Images.ContainsKey('')) {
            if ($themes) { $lines.Add('') }
            $lines.Add("![$Title]($($Images[''] -replace ' ', '%20'))")
        }
    }
    foreach ($entry in $overview) { Add-Entry $entry[0] 2 $entry[0] $entry[1] }
    if ($settings) {
        $lines.Add(''); $lines.Add('## Settings')
        foreach ($entry in $settings) { Add-Entry $entry[0] 3 "Settings: $($entry[0])" $entry[1] }
    }
    if ($other) {
        $lines.Add(''); $lines.Add('## More')
        foreach ($entry in $other) { Add-Entry $entry[0] 3 $entry[0] $entry[1] }
    }
    $path = Join-Path $Folder 'screenshots.md'
    [IO.File]::WriteAllText($path, ($lines -join "`n") + "`n", (New-Object System.Text.UTF8Encoding $false))
    Write-Host "Wrote $path"
}
if ($options['index-only']) {
    if (-not (Test-Path $out)) { throw "Output folder not found: $out" }
    Write-ScreenshotIndex (Resolve-Path $out).Path
    exit 0
}

$exe = $options['exe']
if (-not $exe) {
    if (-not $options['no-build']) {
        & (Join-Path $PSScriptRoot 'build.ps1') --release
    }
    $exe = Join-Path $root 'target\x86_64-pc-windows-msvc\release\WindowsVirtualDesktopHelper.exe'
}
if (-not (Test-Path $exe)) { throw "Executable not found: $exe" }
$exe = (Resolve-Path $exe).Path

Add-Type -ReferencedAssemblies System.Drawing, System.Windows.Forms -TypeDefinition @'
using System;
using System.Drawing;
using System.Drawing.Imaging;
using System.Runtime.InteropServices;
using System.Windows.Forms;
// A plain, non-activating window placed directly behind Settings while capturing, so the
// rounded corners and translucent border show a solid colour instead of the desktop.
class Backdrop : Form {
    public Backdrop(Color color, Rectangle bounds) {
        FormBorderStyle = FormBorderStyle.None;
        ShowInTaskbar = false;
        StartPosition = FormStartPosition.Manual;
        TopMost = true;
        BackColor = color;
        Bounds = bounds;
    }
    protected override bool ShowWithoutActivation { get { return true; } }
    protected override CreateParams CreateParams {
        get { var p = base.CreateParams; p.ExStyle |= 0x08000000 | 0x00000080; return p; } // NOACTIVATE | TOOLWINDOW
    }
}
public static class SettingsShot {
    [DllImport("user32.dll")] static extern bool SetProcessDpiAwarenessContext(IntPtr value);
    [DllImport("user32.dll")] static extern bool SetForegroundWindow(IntPtr hwnd);
    [DllImport("user32.dll")] static extern bool SetWindowPos(IntPtr hwnd, IntPtr after, int x, int y, int cx, int cy, uint flags);
    [DllImport("user32.dll")] static extern bool PostMessage(IntPtr hwnd, uint msg, IntPtr w, IntPtr l);
    [DllImport("user32.dll")] static extern bool GetWindowRect(IntPtr hwnd, out RECT rect);
    [DllImport("dwmapi.dll")] static extern int DwmGetWindowAttribute(IntPtr hwnd, int attribute, out RECT rect, int size);
    [StructLayout(LayoutKind.Sequential)] struct RECT { public int Left, Top, Right, Bottom; }
    public static void DpiAware() { SetProcessDpiAwarenessContext(new IntPtr(-4)); }
    public static void Close(IntPtr hwnd) { PostMessage(hwnd, 0x0010, IntPtr.Zero, IntPtr.Zero); }
    // Centers the visible frame (excluding the invisible resize borders) on the primary work area.
    public static void Center(IntPtr hwnd) {
        RECT outer, visible;
        GetWindowRect(hwnd, out outer);
        if (DwmGetWindowAttribute(hwnd, 9, out visible, Marshal.SizeOf(typeof(RECT))) != 0) visible = outer;
        var area = Screen.PrimaryScreen.WorkingArea;
        int width = visible.Right - visible.Left, height = visible.Bottom - visible.Top;
        int x = area.Left + Math.Max(0, (area.Width - width) / 2) - (visible.Left - outer.Left);
        int y = area.Top + Math.Max(0, (area.Height - height) / 2) - (visible.Top - outer.Top);
        SetWindowPos(hwnd, IntPtr.Zero, x, y, 0, 0, 0x0001 | 0x0004 | 0x0010); // NOSIZE | NOZORDER | NOACTIVATE
    }
    static void Pump(int ms) {
        var end = DateTime.Now.AddMilliseconds(ms);
        while (DateTime.Now < end) { Application.DoEvents(); System.Threading.Thread.Sleep(20); }
    }
    // Captures what DWM composes on screen (Mica included), with the window held topmost
    // above a solid backdrop of the given colour.
    public static void Capture(IntPtr hwnd, string path, string backdrop) {
        const uint NoSizeMoveActivate = 0x0001 | 0x0002 | 0x0010;
        RECT r;
        if (DwmGetWindowAttribute(hwnd, 9, out r, Marshal.SizeOf(typeof(RECT))) != 0) throw new Exception("Could not read window bounds");
        var bounds = Rectangle.FromLTRB(r.Left, r.Top, r.Right, r.Bottom);
        var cover = bounds;
        cover.Inflate(64, 64);
        using (var form = new Backdrop(ColorTranslator.FromHtml(backdrop), cover)) {
            form.Show();
            Pump(100);
            SetWindowPos(hwnd, new IntPtr(-1), 0, 0, 0, 0, NoSizeMoveActivate);
            SetForegroundWindow(hwnd);
            Pump(400);
            try {
                using (var bitmap = new Bitmap(bounds.Width, bounds.Height))
                using (var graphics = Graphics.FromImage(bitmap)) {
                    graphics.CopyFromScreen(bounds.Left, bounds.Top, 0, 0, bitmap.Size);
                    bitmap.Save(path, ImageFormat.Png);
                }
            } finally {
                SetWindowPos(hwnd, new IntPtr(-2), 0, 0, 0, 0, NoSizeMoveActivate);
                form.Close();
            }
        }
    }
}
'@
[SettingsShot]::DpiAware()

$appData = Join-Path ([IO.Path]::GetTempPath()) "wvdh-screenshots-$PID"
New-Item -ItemType Directory -Force $appData | Out-Null
New-Item -ItemType Directory -Force $out | Out-Null
$previousAppData = $env:APPDATA
$env:APPDATA = $appData
try {
    foreach ($theme in $themes) {
        # The theme goes in the throwaway config, not on the command line: a command-line
        # option would show a "Set by command-line options" notice on the General page.
        $configDir = Join-Path $appData 'WindowsVirtualDesktopHelper'
        New-Item -ItemType Directory -Force $configDir | Out-Null
        Set-Content -Encoding ASCII (Join-Path $configDir 'WindowsVirtualDesktopHelper.exe.config') "general.theme: $theme"
        foreach ($page in $selected) {
            $index = [array]::IndexOf($pages, $page) + 1
            $file = Join-Path $out ('WindowsVirtualDesktopHelper-Screenshot-{0:00}-{1}-{2}.png' -f $index, $page, $theme)
            $process = Start-Process -FilePath $exe -PassThru -ArgumentList @(
                '--settings-ui', '--ui-page', $page, '--ui-width', $width, '--ui-height', $height)
            try {
                $deadline = (Get-Date).AddSeconds(20)
                do {
                    Start-Sleep -Milliseconds 200
                    $process.Refresh()
                    if ($process.HasExited) { throw "Settings exited early (code $($process.ExitCode)) on page '$page'" }
                } until ($process.MainWindowHandle -ne 0 -and $process.MainWindowTitle -like 'Settings*' -or (Get-Date) -gt $deadline)
                if ($process.MainWindowHandle -eq 0) { throw "Settings window did not appear for page '$page'" }
                [SettingsShot]::Center($process.MainWindowHandle)
                Start-Sleep -Milliseconds $delay
                [SettingsShot]::Capture($process.MainWindowHandle, $file, $backdrop[$theme])
                Write-Host "Saved $file"
            } finally {
                if (-not $process.HasExited) {
                    [SettingsShot]::Close($process.MainWindowHandle)
                    if (-not $process.WaitForExit(5000)) { $process.Kill() }
                }
            }
        }
    }
} finally {
    $env:APPDATA = $previousAppData
    Remove-Item -Recurse -Force $appData -ErrorAction SilentlyContinue
}
Write-ScreenshotIndex (Resolve-Path $out).Path
